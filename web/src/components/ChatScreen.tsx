// Pre-generated by the server's Arabic neural voice and cached on disk, so the
// voice test still speaks Arabic when the online TTS service is unreachable.
const VOICE_SAMPLE_TEXT =
  "مرحبًا بك في مساعد المصنع. هذا اختبار للصوت العربي.";

interface UiMessage {
  id: string;
  role: "user" | "assistant";
  text: string;
  source?: ChatSource;
  image?: string;
  session?: AssistantResponse | null;
  equipment?: EquipmentSummary[];
  components?: ComponentSummary[];
  quickReplies?: string[];
}

interface SendOptions {
  image?: string | null;
  mode?: "auto" | "describe" | "identify";
}

let messageSequence = 0;

function nextMessageId(): string {
  messageSequence += 1;
  return `msg-${Date.now().toString(36)}-${messageSequence}`;
}

function toMessage(error: unknown): string {
  if (error instanceof ApiError) return error.message;
  if (error instanceof Error) return error.message;
  return "حدث خطأ غير متوقع.";
}

function toAssistantMessage(response: ChatResponse): UiMessage {
  return {
    id: nextMessageId(),
    role: "assistant",
    text: response.message_ar,
    source: response.source,
    session: response.session,
    equipment: response.equipment,
    components: response.components,
    quickReplies: response.quick_replies,
  };
}

function quickRepliesForSession(session: AssistantResponse): string[] {
  if (session.state === "AWAITING_LOTO") {
    return ["تحذيرات السلامة", "كيف أكمل العزل؟", "اعرض القطع"];
  }
  if (session.state === "READY" || session.state === "IN_PROGRESS") {
    return ["الخطوة التالية", "كم العزم؟", "أعد الخطوة", "تحذيرات السلامة"];
  }
  if (session.state === "COMPLETED") {
    return ["ابدأ جلسة جديدة", "ما المعدات المتاحة؟"];
  }
  return ["اعرض القطع", "افتح الكاميرا", "ما المعدات المتاحة؟"];
}

function shortEquipment(name: string): string {
  return name.replace(/^Caterpillar\s+/i, "").replace(/^Siemens\s+/i, "");
}

function renderInline(text: string) {
  return text
    .split(/(\*\*[^*]+\*\*|`[^`]+`)/g)
    .filter((part) => part.length > 0)
    .map((part, index) => {
      if (part.startsWith("**") && part.endsWith("**") && part.length > 4) {
        return <strong key={index}>{part.slice(2, -2)}</strong>;
      }
      if (part.startsWith("`") && part.endsWith("`") && part.length > 2) {
        return <code key={index}>{part.slice(1, -1)}</code>;
      }
      return <span key={index}>{part}</span>;
    });
}

function ChatText({ text }: { text: string }) {
  const lines = text.split("\n");
  return (
    <div className="chat-text">
      {lines.map((line, index) => {
        const clean = line.replace(/^#{1,6}\s*/, "");
        if (!clean.trim()) {
          return <span key={index} className="chat-gap" aria-hidden="true" />;
        }
        return <p key={index}>{renderInline(clean)}</p>;
      })}
    </div>
  );
}

function equipmentGlyph(name: string) {
  if (/siemens|s7|panel|لوحة/i.test(name)) return <BoltIcon size={21} />;
  if (/320|excavator|حفار/i.test(name)) return <TruckIcon size={21} />;
  return <EngineIcon size={21} />;
}

function EquipmentStrip({
  items,
  busy,
  onPick,
}: {
  items: EquipmentSummary[];
  busy: boolean;
  onPick: (name: string) => void;
}) {
  return (
    <div className="chat-equipment-grid">
      {items.map((item) => (
        <button
          key={item.equipment_family}
          type="button"
          className="chat-equipment-card"
          onClick={() => onPick(item.equipment_family)}
          disabled={busy}
        >
          <span className="chat-equipment-icon">{equipmentGlyph(item.equipment_family)}</span>
          <span className="chat-equipment-copy">
            <strong>{item.equipment_family}</strong>
            <small>
              {item.manufacturer} · {item.component_count} قطع
            </small>
          </span>
        </button>
      ))}
    </div>
  );
}

function ComponentStrip({
  items,
  busy,
  onPick,
}: {
  items: ComponentSummary[];
  busy: boolean;
  onPick: (partNumber: string) => void;
}) {
  return (
    <div className="chat-component-list">
      {items.map((item) => (
        <button
          key={item.part_number}
          type="button"
          className="chat-component-item"
          onClick={() => onPick(item.part_number)}
          disabled={busy}
        >
          <bdi dir="ltr" className="chat-part-number">
            {item.part_number}
          </bdi>
          <span>{item.arabic_name}</span>
          <small dir="ltr">{item.english_name}</small>
        </button>
      ))}
    </div>
  );
}

function SessionCards({
  session,
  busy,
  onConfirmLoto,
  onStep,
  onSpeak,
  onPickCandidate,
}: {
  session: AssistantResponse;
  busy: boolean;
  onConfirmLoto: (ids: string[]) => void;
  onStep: (action: "next" | "prev" | "repeat") => void;
  onSpeak: (text: string) => void;
  onPickCandidate: (partNumber: string) => void;
}) {
  const safety = session.safety_lockout;
  const showSafety =
    safety !== null &&
    (safety.loto_required || safety.warnings_ar.length > 0 || safety.acknowledged_by_technician);

  return (
    <div className="chat-session-cards">
      {session.identified_component && (
        <ComponentCard component={session.identified_component} />
      )}

      {showSafety && safety && (
        <SafetyPanel protocol={safety} busy={busy} onConfirm={onConfirmLoto} />
      )}

      {session.current_step && (
        <StepCard
          session={session}
          busy={busy}
          onStep={onStep}
          onSpeak={onSpeak}
        />
      )}

      {!session.identified_component && session.retrieval_candidates.length > 0 && (
        <div className="chat-candidates">
          <span className="chat-candidates-title">نتائج محتملة من قاعدة المعرفة</span>
          <div className="chat-candidate-list">
            {session.retrieval_candidates.map((candidate) => (
              <button
                key={candidate.part_number}
                type="button"
                onClick={() => onPickCandidate(candidate.part_number)}
                disabled={busy}
              >
                <bdi dir="ltr">{candidate.part_number}</bdi>
                <span>{candidate.arabic_name}</span>
              </button>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}

export function ChatScreen({ onLogout }: { onLogout?: () => void }) {
  const [messages, setMessages] = useState<UiMessage[]>([]);
  const [draft, setDraft] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [session, setSession] = useState<AssistantResponse | null>(null);
  const [cameraOpen, setCameraOpen] = useState(false);
  const [listening, setListening] = useState(false);
  const [micError, setMicError] = useState<string | null>(null);
  const [voiceError, setVoiceError] = useState<string | null>(null);
  const [autoSpeak, setAutoSpeak] = useState(true);
  const [health, setHealth] = useState<HealthResponse | null>(null);

  const messagesRef = useRef<UiMessage[]>([]);
  const sessionRef = useRef<AssistantResponse | null>(null);
  const busyRef = useRef(false);
  const autoSpeakRef = useRef(autoSpeak);
  const listeningRef = useRef(false);
  const recognitionRef = useRef<any>(null);
  const lastImageRef = useRef<string | null>(null);
  const hasInteractedRef = useRef(false);
  const sendRef = useRef<(text: string, options?: SendOptions) => void>(() => undefined);
  const startListeningRef = useRef<() => void>(() => undefined);
  const stopListeningRef = useRef<() => void>(() => undefined);
  const scrollAnchorRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLTextAreaElement>(null);

  useEffect(() => {
    messagesRef.current = messages;
  }, [messages]);

  useEffect(() => {
    sessionRef.current = session;
  }, [session]);

  useEffect(() => {
    autoSpeakRef.current = autoSpeak;
  }, [autoSpeak]);

  useEffect(() => {
    const element = inputRef.current;
    if (!element) return;
    element.style.height = "auto";
    element.style.height = `${Math.min(element.scrollHeight, 128)}px`;
  }, [draft]);

  useEffect(() => {
    scrollAnchorRef.current?.scrollIntoView({
      behavior: busy ? "smooth" : "auto",
      block: "end",
    });
  }, [messages, busy]);

  useEffect(() => {
    return () => {
      try {
        recognitionRef.current?.abort();
      } catch {
        /* ignore */
      }
      stopSpeaking();
    };
  }, []);

  function applyAction(action: ChatAction | null) {
    if (!action) return;
    if (action === "open_camera") setCameraOpen(true);
    if (action === "close_camera") setCameraOpen(false);
    if (action === "start_listening") {
      window.setTimeout(() => startListeningRef.current(), 450);
    }
    if (action === "stop_listening") stopListeningRef.current();
  }

  function applyChatResponse(response: ChatResponse, speak = true) {
    setMessages((current) => [...current, toAssistantMessage(response)]);
    if (response.session) {
      setSession(response.session);
      sessionRef.current = response.session;
    }
    if (
      speak &&
      autoSpeakRef.current &&
      hasInteractedRef.current &&
      response.action !== "start_listening"
    ) {
      speakArabic(response.message_ar, true);
    }
    applyAction(response.action);
  }

  function applySessionResponse(response: AssistantResponse) {
    const message: UiMessage = {
      id: nextMessageId(),
      role: "assistant",
      text: response.assistant_message_ar,
      source: "assistant",
      session: response,
      quickReplies: quickRepliesForSession(response),
    };
    setMessages((current) => [...current, message]);
    setSession(response);
    sessionRef.current = response;
    if (autoSpeakRef.current) speakArabic(response.assistant_message_ar, true);
  }

  function reportError(err: unknown) {
    const message = toMessage(err);
    setError(message);
    setMessages((current) => [
      ...current,
      {
        id: nextMessageId(),
        role: "assistant",
        source: "system",
        text: `تعذر تنفيذ الطلب: ${message}`,
      },
    ]);
  }

  async function loadWelcome() {
    setBusy(true);
    busyRef.current = true;
    try {
      const [healthResult, welcome] = await Promise.all([
        api.health().catch(() => null),
        api.chat({ message: "", history: [] }),
      ]);
      if (healthResult) setHealth(healthResult);
      setMessages([toAssistantMessage(welcome)]);
    } catch (err) {
      reportError(err);
    } finally {
      busyRef.current = false;
      setBusy(false);
    }
  }

  useEffect(() => {
    let cancelled = false;
    setBusy(true);
    busyRef.current = true;
    Promise.all([
      api.health().catch(() => null),
      api.chat({ message: "", history: [] }),
    ])
      .then(([healthResult, welcome]) => {
        if (cancelled) return;
        if (healthResult) setHealth(healthResult);
        setMessages([toAssistantMessage(welcome)]);
      })
      .catch((err) => {
        if (!cancelled) reportError(err);
      })
      .finally(() => {
        if (cancelled) return;
        busyRef.current = false;
        setBusy(false);
      });
    return () => {
      cancelled = true;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  async function send(rawText: string, options?: SendOptions) {
    const text = rawText.trim();
    const image = options?.image || null;
    if ((!text && !image) || busyRef.current) return;

    hasInteractedRef.current = true;
    setDraft("");
    setError(null);
    setMicError(null);
    if (image) lastImageRef.current = image;

    const displayText =
      text ||
      (options?.mode === "identify" ? "حدد القطعة في هذه الصورة" : "صورة من الكاميرا");
    const history: ChatTurn[] = messagesRef.current
      .filter((message) => message.role === "user" || message.text.length > 0)
      .slice(-12)
      .map((message) => ({
        role: message.role,
        content: message.text.slice(0, 2000),
      }));

    const userMessage: UiMessage = {
      id: nextMessageId(),
      role: "user",
      text: displayText,
      image: image || undefined,
    };
    setMessages((current) => [...current, userMessage]);

    busyRef.current = true;
    setBusy(true);
    try {
      const response = await api.chat({
        message: text,
        image_base64: image,
        session_id: sessionRef.current?.session_id ?? null,
        history,
        mode: options?.mode ?? "auto",
      });
      applyChatResponse(response);
    } catch (err) {
      reportError(err);
    } finally {
      busyRef.current = false;
      setBusy(false);
    }
  }

  async function handleConfirmLoto(ids: string[]) {
    const current = sessionRef.current;
    if (!current || busyRef.current) return;
    busyRef.current = true;
    setBusy(true);
    setError(null);
    try {
      const response = await api.confirmLoto(current.session_id, ids);
      applySessionResponse(response);
    } catch (err) {
      reportError(err);
    } finally {
      busyRef.current = false;
      setBusy(false);
    }
  }

  async function handleStep(action: "next" | "prev" | "repeat") {
    const current = sessionRef.current;
    if (!current || busyRef.current) return;
    busyRef.current = true;
    setBusy(true);
    setError(null);
    try {
      const response = await api.step(current.session_id, action);
      applySessionResponse(response);
    } catch (err) {
      reportError(err);
    } finally {
      busyRef.current = false;
      setBusy(false);
    }
  }

  function handleSpeak(text: string) {
    setVoiceError(null);
    void speakArabic(text, true).then((played) => {
      if (!played) {
        setVoiceError("تعذر تشغيل الصوت العربي. تحقق من اتصال خدمة النطق.");
      }
    });
  }

  async function testArabicVoice() {
    setVoiceError(null);
    const played = await speakArabic(VOICE_SAMPLE_TEXT, true);
    if (!played) {
      setVoiceError("تعذر تشغيل الصوت العربي. تحقق من اتصال خدمة النطق.");
    }
  }

  function stopListening() {
    try {
      recognitionRef.current?.abort();
    } catch {
      /* ignore */
    }
    recognitionRef.current = null;
    listeningRef.current = false;
    setListening(false);
  }

  async function startListening() {
    if (listeningRef.current) return;
    setMicError(null);
    if (!recognitionSupported()) {
      setMicError("هذا المتصفح لا يدعم تحويل الكلام إلى نص. استخدم الكتابة.");
      return;
    }
    if (!navigator.mediaDevices?.getUserMedia) {
      setMicError("لا يمكن الوصول إلى الميكروفون من هذه الصفحة. استخدم HTTPS أو localhost.");
      return;
    }

    try {
      const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
      stream.getTracks().forEach((track) => track.stop());
    } catch {
      setMicError("تعذر الوصول إلى الميكروفون. اسمح بالإذن من إعدادات المتصفح.");
      return;
    }

    const recognition = createArabicRecognizer();
    if (!recognition) {
      setMicError("خدمة التعرف الصوتي غير متاحة في هذا المتصفح.");
      return;
    }

    recognitionRef.current = recognition;

    recognition.onstart = () => {
      listeningRef.current = true;
      setListening(true);
      setMicError(null);
    };

    recognition.onend = () => {
      listeningRef.current = false;
      setListening(false);
    };

    recognition.onerror = (event: any) => {
      listeningRef.current = false;
      setListening(false);
      const code = event?.error;
      if (code === "aborted") return;
      if (code === "not-allowed" || code === "service-not-allowed") {
        setMicError("لم يُسمح باستخدام الميكروفون. راجع إذن الموقع في المتصفح.");
      } else if (code === "no-speech") {
        setMicError("لم أسمع كلامًا. اضغط الميكروفون وحاول مرة أخرى.");
      } else if (code === "network") {
        setMicError("خدمة التعرف الصوتي غير متاحة دون اتصال. يمكنك الكتابة.");
      } else {
        setMicError("تعذر التعرف على الصوت. حاول مرة أخرى أو استخدم الكتابة.");
      }
    };

    recognition.onresult = (event: any) => {
      const transcript = Array.from(event.results)
        .map((result: any) => result?.[0]?.transcript || "")
        .join(" ")
        .trim();
      if (transcript) {
        sendRef.current(transcript);
      }
    };

    try {
      listeningRef.current = true;
      setListening(true);
      recognition.start();
    } catch {
      listeningRef.current = false;
      setListening(false);
      setMicError("تعذر بدء الاستماع. أغلق أي تطبيق آخر يستخدم الميكروفون ثم أعد المحاولة.");
    }
  }

  function handleQuickReply(reply: string) {
    if (reply === "حدد القطعة في هذه الصورة" && lastImageRef.current) {
      void send("حدد القطعة", {
        image: lastImageRef.current,
        mode: "identify",
      });
      return;
    }
    void send(reply);
  }

  function handleCameraCapture(image: string, mode: "describe" | "identify") {
    setCameraOpen(false);
    lastImageRef.current = image;
    void send(mode === "identify" ? "حدد القطعة" : "", { image, mode });
  }

  function resetConversation() {
    stopListening();
    stopSpeaking();
    setCameraOpen(false);
    setSession(null);
    sessionRef.current = null;
    lastImageRef.current = null;
    setError(null);
    setMicError(null);
    setMessages([]);
    void loadWelcome();
  }

  function toggleSpeaking() {
    setAutoSpeak((current) => {
      const next = !current;
      if (!next) stopSpeaking();
      return next;
    });
  }

  function handleComposerKeyDown(event: KeyboardEvent<HTMLTextAreaElement>) {
    if (event.key === "Enter" && !event.shiftKey && !event.nativeEvent.isComposing) {
      event.preventDefault();
      void send(draft);
    }
  }

  sendRef.current = send;
  startListeningRef.current = startListening;
  stopListeningRef.current = stopListening;

  const latestSessionMessageId = useMemo(() => {
    for (let index = messages.length - 1; index >= 0; index -= 1) {
      if (messages[index].session) return messages[index].id;
    }
    return null;
  }, [messages]);

  const lastMessage = messages[messages.length - 1];
  const quickReplies =
    !busy && lastMessage?.role === "assistant" ? lastMessage.quickReplies ?? [] : [];
  const online = health?.status === "online";

  return (
    <div className="chat-shell">
      <header className="chat-header">
        <div className="chat-brand">
          <span className="chat-brand-mark">
            <SparkIcon size={21} />
          </span>
          <div className="chat-brand-copy">
            <strong>مسبار</strong>
            <small>
              <span className={`chat-status-dot ${online ? "online" : "offline"}`} />
              {health === null
                ? "جارٍ الاتصال…"
                : online
                  ? health.chat_ready
                    ? "محادثة ذكية + قاعدة معرفة"
                    : "أوامر محلية آمنة"
                  : "الخادم غير متصل"}
            </small>
          </div>
        </div>

        <div className="chat-header-actions">
          {session && (
            <span className="chat-session-chip" title={session.equipment_model}>
              <b>{shortEquipment(session.equipment_model)}</b>
              <small>{STATE_LABELS[session.state]}</small>
            </span>
          )}
          <button
            type="button"
            className="chat-icon-btn chat-voice-test"
            onClick={() => void testArabicVoice()}
            aria-label="اختبار الصوت العربي"
            title="اختبار الصوت العربي"
          >
            <PlayIcon size={18} />
          </button>
          <button
            type="button"
            className={`chat-icon-btn ${autoSpeak ? "is-on" : ""}`}
            onClick={toggleSpeaking}
            aria-label={autoSpeak ? "إيقاف القراءة الصوتية" : "تشغيل القراءة الصوتية"}
            title={autoSpeak ? "القراءة الصوتية مفعّلة" : "القراءة الصوتية متوقفة"}
          >
            {autoSpeak ? <VolumeIcon size={20} /> : <VolumeOffIcon size={20} />}
          </button>
          <button
            type="button"
            className="chat-icon-btn"
            onClick={() => setCameraOpen(true)}
            aria-label="فتح الكاميرا"
            title="فتح الكاميرا"
          >
            <CameraIcon size={20} />
          </button>
          <button
            type="button"
            className="chat-icon-btn"
            onClick={resetConversation}
            aria-label="محادثة جديدة"
            title="محادثة جديدة"
          >
            <RotateCcwIcon size={19} />
          </button>
          {onLogout && (
            <button
              type="button"
              className="chat-logout-btn"
              onClick={onLogout}
              aria-label="تسجيل الخروج"
            >
              خروج
            </button>
          )}
        </div>
      </header>

      <main className="chat-main" aria-live="polite">
        <div className="chat-thread">
          {messages.map((message) => {
            const showSessionCards =
              message.session !== undefined && message.id === latestSessionMessageId;
            return (
              <article key={message.id} className={`chat-msg ${message.role}`}>
                {message.role === "assistant" && (
                  <span className="chat-avatar" aria-hidden="true">
                    <SparkIcon size={17} />
                  </span>
                )}

                <div className="chat-msg-content">
                  {message.role === "assistant" && (
                    <div className="chat-msg-meta">
                      <strong>مسبار</strong>
                      {message.source && (
                        <span className={`chat-source ${message.source}`}>
                          {SOURCE_LABELS[message.source]}
                        </span>
                      )}
                      {message.text && (
                        <button
                          type="button"
                          className="chat-replay"
                          onClick={() => handleSpeak(message.text)}
                          aria-label="قراءة الرد صوتيًا"
                          title="قراءة الرد صوتيًا"
                        >
                          <VolumeIcon size={14} />
                        </button>
                      )}
                    </div>
                  )}

                  {message.image && (
                    <img
                      src={message.image}
                      alt="لقطة من كاميرا المحادثة"
                      className="chat-image"
                    />
                  )}

                  {message.text && (
                    <div className="chat-bubble">
                      <ChatText text={message.text} />
                    </div>
                  )}

                  {message.equipment && message.equipment.length > 0 && (
                    <EquipmentStrip
                      items={message.equipment}
                      busy={busy}
                      onPick={(name) => void send(`ابدأ جلسة على ${name}`)}
                    />
                  )}

                  {message.components && message.components.length > 0 && (
                    <ComponentStrip
                      items={message.components}
                      busy={busy}
                      onPick={(partNumber) =>
                        void send(`حدد القطعة ${partNumber}`)
                      }
                    />
                  )}

                  {showSessionCards && message.session && (
                    <SessionCards
                      session={message.session}
                      busy={busy}
                      onConfirmLoto={(ids) => void handleConfirmLoto(ids)}
                      onStep={(action) => void handleStep(action)}
                      onSpeak={handleSpeak}
                      onPickCandidate={(partNumber) =>
                        void send(`حدد القطعة ${partNumber}`)
                      }
                    />
                  )}
                </div>
              </article>
            );
          })}

          {busy && (
            <article className="chat-msg assistant">
              <span className="chat-avatar" aria-hidden="true">
                <SparkIcon size={17} />
              </span>
              <div className="chat-msg-content">
                <div className="chat-bubble chat-typing" aria-label="جارٍ التفكير">
                  <span />
                  <span />
                  <span />
                </div>
              </div>
            </article>
          )}

          <div ref={scrollAnchorRef} />
        </div>
      </main>

      <footer className="chat-composer">
        {error && (
          <div className="chat-error" role="alert">
            <AlertIcon size={17} />
            <span>{error}</span>
            <button type="button" onClick={() => setError(null)} aria-label="إغلاق التنبيه">
              <CloseIcon size={15} />
            </button>
          </div>
        )}

        {quickReplies.length > 0 && (
          <div className="chat-quick-row" aria-label="اقتراحات سريعة">
            {quickReplies.map((reply) => (
              <button
                key={reply}
                type="button"
                className="chat-quick-chip"
                onClick={() => handleQuickReply(reply)}
                disabled={busy}
              >
                {reply}
              </button>
            ))}
          </div>
        )}

        <div className={`chat-input-row ${listening ? "is-listening" : ""}`}>
          <button
            type="button"
            className="chat-tool-btn"
            onClick={() => setCameraOpen(true)}
            aria-label="فتح الكاميرا"
            title="فتح الكاميرا"
          >
            <CameraIcon size={22} />
          </button>

          <button
            type="button"
            className={`chat-tool-btn mic ${listening ? "is-listening" : ""}`}
            onClick={() => (listening ? stopListening() : void startListening())}
            aria-label={listening ? "إيقاف الاستماع" : "بدء الاستماع"}
            title={listening ? "إيقاف الاستماع" : "التحدث"}
          >
            {listening ? <StopIcon size={20} /> : <MicIcon size={22} />}
            {listening && <span className="chat-mic-ring" aria-hidden="true" />}
          </button>

          <textarea
            ref={inputRef}
            className="chat-input"
            rows={1}
            value={draft}
            onChange={(event) => setDraft(event.target.value)}
            onKeyDown={handleComposerKeyDown}
            placeholder={
              listening
                ? "أستمع الآن… تكلّم بالعربية"
                : "اكتب رسالتك… أو قل: افتح الكاميرا"
            }
            aria-label="نص الرسالة"
          />

          <button
            type="button"
            className="chat-send-btn"
            onClick={() => void send(draft)}
            disabled={busy || !draft.trim()}
            aria-label="إرسال الرسالة"
          >
            {busy ? <span className="chat-spinner" /> : <SendIcon size={20} />}
          </button>
        </div>

        <div className="chat-composer-meta">
          <span className={micError || voiceError ? "is-error" : ""}>
            {micError ||
              voiceError ||
              (listening
                ? "أستمع الآن… سأرسل النص تلقائيًا بعد انتهاء كلامك."
                : "الصوت والكاميرا يعملان من داخل المحادثة.")}
          </span>
          <span className="chat-powered">
            {health?.chat_ready ? "Cohere + قاعدة معرفة محلية" : "قاعدة معرفة محلية"}
          </span>
        </div>
      </footer>

      {cameraOpen && (
        <ChatCamera
          onCapture={handleCameraCapture}
          onClose={() => setCameraOpen(false)}
        />
      )}
    </div>
  );
}
