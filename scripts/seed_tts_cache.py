r"""Seed the offline Arabic voice cache from the bundled sample MP3.

The sample was generated by the same Edge neural voice used by the server, so
the voice test keeps speaking Arabic even when the online service is
unreachable. Run this once after cloning the repository:

    .\.venv\Scripts\python.exe scripts\seed_tts_cache.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.adapters.tts.edge import (  # noqa: E402
    ARABIC_VOICES,
    DEFAULT_ARABIC_VOICE,
    EdgeTtsAdapter,
)
from app.core.config import get_settings  # noqa: E402

SAMPLE_TEXT = "مرحبًا بك في مساعد المصنع. هذا اختبار للصوت العربي."


def main() -> int:
    source = ROOT / "docs" / "test-assets" / "tts-arabic.mp3"
    if not source.is_file() or source.stat().st_size < 1000:
        print(f"[ERROR] ملف العينة غير موجود أو تالف: {source}")
        return 1

    settings = get_settings()
    voice = settings.tts_voice if settings.tts_voice in ARABIC_VOICES else DEFAULT_ARABIC_VOICE
    cache_dir = Path(settings.tts_cache_dir)
    cache_dir.mkdir(parents=True, exist_ok=True)
    target = cache_dir / f"{EdgeTtsAdapter._cache_key(SAMPLE_TEXT, voice)}.mp3"

    if target.is_file() and target.stat().st_size == source.stat().st_size:
        print(f"[OK] الذاكرة الصوتية مهيأة مسبقًا: {target}")
        return 0

    target.write_bytes(source.read_bytes())
    print(f"[OK] نُسخ الصوت العربي إلى الذاكرة المحلية: {target}")
    print(f"     الصوت: {voice} — الحجم: {target.stat().st_size} بايت")
    print("     زر «اختبار الصوت العربي» سيعمل الآن دون اتصال.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
